#!/usr/bin/env node
/**
 * legal/terms.html, legal/privacy.html and legal/rules.html are the only
 * copies of the Terms of Service, Privacy Policy and Rules. This writes them
 * into the launcher (src/renderer/legal.js) and, with --site <dir>, into the
 * website pages (rules.html is created from the terms page the first time).
 *
 *   node scripts/build-legal.js [--site ..\solarclientsite-site]
 *
 * Bump VERSION whenever the text changes so the launcher asks people to
 * accept the new version.
 */
'use strict';

const fs = require('fs');
const path = require('path');

const VERSION = '2026.10.12c';
const UPDATED = 'October 12, 2026';

const ROOT = path.join(__dirname, '..');
const read = (n) => fs.readFileSync(path.join(ROOT, 'legal', n), 'utf8').trim();
const docs = {
  terms: {
    file: 'terms.html', title: 'Terms of Service', crumb: 'Terms of service', body: read('terms.html'),
    description: 'The rules for using the SolarClient website, launcher, and online features, including what you may not copy, how to treat other people, and our limits on liability.',
  },
  privacy: {
    file: 'privacy.html', title: 'Privacy Policy', crumb: 'Privacy policy', body: read('privacy.html'),
    description: 'What information the SolarClient website, launcher, and online features collect, why, how long we keep it, and how to ask us to delete it.',
  },
  rules: {
    file: 'rules.html', title: 'Rules', crumb: 'Rules', body: read('rules.html'),
    description: 'The SolarClient chat and community rules: what is allowed, what is not, and what happens if you break them.',
  },
};

const out = path.join(ROOT, 'src', 'renderer', 'legal.js');
fs.writeFileSync(out, `// Generated by scripts/build-legal.js from legal/*.html. Do not edit by hand.
window.SOLAR_LEGAL = ${JSON.stringify({
  version: VERSION,
  updated: UPDATED,
  terms: docs.terms.body,
  privacy: docs.privacy.body,
  rules: docs.rules.body,
}, null, 2)};
`);
console.log(`[legal] wrote ${path.relative(ROOT, out)} (version ${VERSION})`);

const i = process.argv.indexOf('--site');
if (i > 0) {
  const site = path.resolve(process.argv[i + 1] || '');
  for (const d of Object.values(docs)) {
    const page = path.join(site, d.file);
    let html;
    if (fs.existsSync(page)) {
      html = fs.readFileSync(page, 'utf8');
    } else {
      // New page: start from the terms page and swap the names over.
      const t = docs.terms;
      html = fs.readFileSync(path.join(site, t.file), 'utf8')
        .split(`figgysmp.shop/${t.file}`).join(`figgysmp.shop/${d.file}`)
        .split(`${t.title} | SolarClient`).join(`${d.title} | SolarClient`)
        .split(`"name": "${t.crumb}"`).join(`"name": "${d.crumb}"`)
        .split(`<span aria-current="page">${t.crumb}</span>`).join(`<span aria-current="page">${d.crumb}</span>`)
        .split(`<h1 class="article-title">${t.title}</h1>`).join(`<h1 class="article-title">${d.title}</h1>`);
      console.log(`[legal] creating ${page}`);
    }
    const open = '<div class="prose">';
    const close = '<hr class="divider">';
    const a = html.indexOf(open);
    const b = html.indexOf(close, a);
    if (a < 0 || b < 0) throw new Error(`${d.file}: could not find the article body`);
    const indented = d.body.split(/\r?\n/).map((l) => (l ? `          ${l}` : '')).join('\n');
    html = `${html.slice(0, a + open.length)}\n${indented}\n          ${html.slice(b)}`;
    html = html.replace(/(<span>Last updated: )[^<]*(<\/span>)/, `$1${UPDATED}$2`);
    html = html.replace(/(<meta (?:name|property)="(?:description|og:description|twitter:description)" content=")[^"]*(")/g, `$1${d.description}$2`);
    html = html.replace(new RegExp(`${d.title}\\s*(?:\\u2014|&mdash;|\\u2013|&ndash;|-)\\s*SolarClient`, 'g'), `${d.title} | SolarClient`);
    fs.writeFileSync(page, html);
    console.log(`[legal] updated ${page}`);
  }
}
